android {
  namespace = "com.example"
  compileSdk { version = release(36) { minorApiLevel = 1 } }

  defaultConfig {
    applicationId = "com.aistudio.creditcards.qwvpkz"
    minSdk = 24
    targetSdk = 36
    // Incrementa la base de versión a 100 + appVersionCode (o 100 por defecto) para
    // garantizar que cualquier APK nuevo siempre tenga un versionCode superior al instalado
    // previamente, permitiendo que Android lo instale directamente como una actualización.
    val runNum = (project.findProperty("appVersionCode") as String?)?.toIntOrNull() ?: 0
    versionCode = 100 + runNum
    versionName = "1.1.$runNum"

    testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
  }

  signingConfigs {
    create("release") {
      val keystorePath = System.getenv("KEYSTORE_PATH") ?: "${rootDir}/my-upload-key.jks"
      storeFile = file(keystorePath)
      storePassword = System.getenv("STORE_PASSWORD")
      keyAlias = "upload"
      keyPassword = System.getenv("KEY_PASSWORD")
    }
    create("debugConfig") {
      val ksFile = file("${rootDir}/debug.keystore")
      val b64File = file("${rootDir}/debug.keystore.base64")
      if (!ksFile.exists() && b64File.exists()) {
        try {
          val decoded = Base64.getDecoder().decode(b64File.readText().trim())
          ksFile.writeBytes(decoded)
        } catch (e: Exception) {
          logger.warn("No se pudo decodificar debug.keystore.base64: ${e.message}")
        }
      }
      storeFile = ksFile
      storePassword = "android"
      keyAlias = "androiddebugkey"
      keyPassword = "android"
    }
  }

  buildTypes {
    release {
      isCrunchPngs = false
      // Antes deshabilitado (isMinifyEnabled = false): la app nunca ofuscaba/reducía su código en
      // release. Se habilita con reglas explícitas en proguard-rules.pro para los modelos de datos
      // y Firebase, que son las clases con más riesgo de romperse con la ofuscación por defecto.
      isMinifyEnabled = true
      isShrinkResources = true
      proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
      signingConfig = signingConfigs.getByName("release")
    }
    debug { signingConfig = signingConfigs.getByName("debugConfig") }
  }
  compileOptions {
    sourceCompatibility = JavaVersion.VERSION_11
    targetCompatibility = JavaVersion.VERSION_11
  }
  buildFeatures {
    compose = true
    buildConfig = true
  }
  testOptions { unitTests { isIncludeAndroidResources = true } }
  dependenciesInfo {
    includeInApk = false
    includeInBundle = true
  }
}

